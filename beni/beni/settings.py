def _load_project_env():
    env_file = BASE_DIR / ".env"
    try:
        lines = env_file.read_text(encoding="utf-8-sig").splitlines()
    except FileNotFoundError:
        return
    except OSError as exc:
        raise ImproperlyConfigured(
            "Unable to read the project .env file."
        ) from exc

    for line_number, line in enumerate(lines, start=1):
        entry = line.strip()
        if not entry or entry.startswith("#"):
            continue
        if entry.startswith("export "):
            entry = entry[len("export "):].lstrip()

        name, separator, raw_value = entry.partition("=")
        name = name.strip()
        if not separator or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
            raise ImproperlyConfigured(
                f"Invalid entry in the project .env file on line {line_number}."
            )

        value = raw_value.strip()
        quote = None
        escaped = False
        for index, character in enumerate(value):
            if escaped:
                escaped = False
            elif character == "\\" and quote != "'":
                escaped = True
            elif quote:
                if character == quote:
                    quote = None
            elif character in ("'", '"'):
                quote = character
            elif character == "#" and (index == 0 or value[index - 1].isspace()):
                value = value[:index].rstrip()
                break

        try:
            parsed_parts = shlex.split(value, comments=False, posix=True)
        except ValueError as exc:
            raise ImproperlyConfigured(
                f"Invalid quoted value in the project .env file on line {line_number}."
            ) from exc

        os.environ.setdefault(name, " ".join(parsed_parts))


_load_project_env()


